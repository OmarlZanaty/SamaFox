CREATE TABLE IF NOT EXISTS "EmojiList" (
  "id" SERIAL PRIMARY KEY, "nameAr" TEXT NOT NULL, "imageUrl" TEXT,
  "sortOrder" INTEGER NOT NULL DEFAULT 0, "isActive" BOOLEAN NOT NULL DEFAULT true,
  "minVip" INTEGER NOT NULL DEFAULT 0, "userIds" INTEGER[] DEFAULT ARRAY[]::INTEGER[],
  "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP, "updatedAt" TIMESTAMP(3) NOT NULL
);
CREATE TABLE IF NOT EXISTS "EmojiItem" (
  "id" SERIAL PRIMARY KEY, "listId" INTEGER NOT NULL, "name" TEXT NOT NULL, "imageUrl" TEXT NOT NULL,
  "sortOrder" INTEGER NOT NULL DEFAULT 0, "isActive" BOOLEAN NOT NULL DEFAULT true,
  "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT "EmojiItem_listId_fkey" FOREIGN KEY ("listId") REFERENCES "EmojiList"("id") ON DELETE CASCADE ON UPDATE CASCADE
);
CREATE INDEX IF NOT EXISTS "EmojiItem_listId_idx" ON "EmojiItem"("listId");
